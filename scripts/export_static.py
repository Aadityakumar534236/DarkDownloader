"""Render DarkDownloader's Jinja pages as a Cloudflare Pages static site."""

from pathlib import Path
import shutil
import sys

from jinja2 import Environment, FileSystemLoader, select_autoescape


ROOT = Path(__file__).resolve().parents[1]
TEMPLATE_DIR = ROOT / "app" / "templates"
STATIC_DIR = ROOT / "app" / "static"
OUTPUT_DIR = ROOT / "site"
MARKER = ".darkdownloader-export"
MARKER_CONTENT = "Generated by scripts/export_static.py; safe to replace.\n"

PAGES = (
    ("home.html", "index.html", "home", "Your media. Your way."),
    ("download.html", "download.html", "download", "Download from URL"),
    ("batch.html", "batch.html", "batch", "Batch processing"),
    ("history.html", "history.html", "history", "Download history"),
    ("sources.html", "sources.html", "sources", "Supported sources"),
    ("settings.html", "settings.html", "settings", "Settings"),
    ("help.html", "help.html", "help", "Help and diagnostics"),
    ("privacy.html", "privacy.html", "privacy", "Privacy"),
    ("copyright.html", "copyright.html", "copyright", "Copyright"),
    ("not_found.html", "404.html", "not-found", "Page not found"),
)

ASSETS = (
    "css/styles.css",
    "js/app.js",
    "js/theme-init.js",
    "icons/favicon.svg",
)


def prepare_output(output_dir: Path) -> None:
    if output_dir.is_symlink():
        raise RuntimeError(f"Refusing to write through a symlink: {output_dir}")
    if output_dir.exists():
        marker = output_dir / MARKER
        if not marker.is_file() or marker.read_text(encoding="utf-8") != MARKER_CONTENT:
            if any(output_dir.iterdir()):
                raise RuntimeError(
                    f"{output_dir} is not a recognized generated export. "
                    "Move its contents or choose an empty directory before exporting."
                )
        else:
            resolved = output_dir.resolve()
            if resolved != OUTPUT_DIR.resolve():
                raise RuntimeError(f"Refusing to replace generated output outside {OUTPUT_DIR}")
            shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / MARKER).write_text(MARKER_CONTENT, encoding="utf-8")


def export_site(output_dir: Path = OUTPUT_DIR) -> list[Path]:
    output_dir = Path(output_dir)
    prepare_output(output_dir)

    environment = Environment(
        loader=FileSystemLoader(str(TEMPLATE_DIR)),
        autoescape=select_autoescape(enabled_extensions=("html",)),
    )
    generated = []
    for template_name, output_name, page, title in PAGES:
        template = environment.get_template(template_name)
        rendered = template.render(page=page, title=title, static_export=True)
        destination = output_dir / output_name
        with destination.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(rendered)
        generated.append(destination)

    for asset in ASSETS:
        source = STATIC_DIR / asset
        if not source.is_file():
            raise FileNotFoundError(f"Required static asset is missing: {source}")
        destination = output_dir / "static" / asset
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
        generated.append(destination)

    for filename in ("manifest.webmanifest", "service-worker.js"):
        source = STATIC_DIR / filename
        if not source.is_file():
            raise FileNotFoundError(f"Required root asset is missing: {source}")
        destination = output_dir / filename
        shutil.copy2(source, destination)
        generated.append(destination)

    return generated


def main() -> int:
    try:
        generated = export_site()
    except (OSError, RuntimeError, FileNotFoundError) as error:
        print(f"Static export failed: {error}", file=sys.stderr)
        return 1
    print(f"Exported {len(generated)} pages and assets to {OUTPUT_DIR}")
    print("Cloudflare Pages clean URLs: /download, /batch, /history, etc.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
